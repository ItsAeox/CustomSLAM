#!/usr/bin/env python3
"""Generate ORB-SLAM3 (settings v1.0) YAML files from the datasets' own calibration files.

Nothing is tuned here: camera/IMU values come from the sequence calibration, ORB extractor
parameters are ORB-SLAM3's published defaults for the closest dataset it ships configs for
(TUM-VI for TUM-VIE, KITTI odometry for KITTI raw).

  make_settings.py tumvie --seq <seq dir> --out tumvie.yaml
  make_settings.py kitti  --seq <drive_sync dir> --out kitti.yaml
"""
import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "eval"))
from common import T_from_pose_dict, find_up, load_tumvie_calib, read_kitti_calib  # noqa: E402

VIEWER = """Viewer.KeyFrameSize: 0.05
Viewer.KeyFrameLineWidth: 1.0
Viewer.GraphLineWidth: 0.9
Viewer.PointSize: 2.0
Viewer.CameraSize: 0.08
Viewer.CameraLineWidth: 3.0
Viewer.ViewpointX: 0.0
Viewer.ViewpointY: -0.7
Viewer.ViewpointZ: -3.5
Viewer.ViewpointF: 500.0
"""


def tumvie(seq: Path) -> str:
    c = load_tumvie_calib(seq)
    cam = c["intrinsics"][0]
    assert cam["camera_type"].lower() == "kb4", cam["camera_type"]
    k = cam["intrinsics"]
    w, h = c["resolution"][0]
    T_b_c = T_from_pose_dict(c["T_imu_cam"][0])  # Basalt T_imu_cam = imu-from-cam = ORB-SLAM3 T_b_c1

    # IMU noise: use the dataset calibration if present (Basalt stores continuous-time densities),
    # otherwise the TUM-VI values shipped with ORB-SLAM3 (same IMU model, BMI160).
    def first(key, default):
        v = c.get(key)
        if v is None:
            return default, "ORB-SLAM3 TUM-VI default"
        v = np.atleast_1d(np.asarray(v, dtype=float))
        return float(np.max(v)), f"from camera-calibration.json:{key}"

    ng, sng = first("gyro_noise_std", 0.00016)
    na, sna = first("accel_noise_std", 0.0028)
    gw, sgw = first("gyro_bias_std", 0.000022)
    aw, saw = first("accel_bias_std", 0.00086)
    rate = float(c.get("imu_update_rate", 200.0))
    data = ", ".join(f"{x:.12f}" for x in T_b_c.reshape(-1))
    return f"""%YAML:1.0
# Generated by make_settings.py from {seq}/camera-calibration.json
File.version: "1.0"
Camera.type: "KannalaBrandt8"
Camera1.fx: {k['fx']}
Camera1.fy: {k['fy']}
Camera1.cx: {k['cx']}
Camera1.cy: {k['cy']}
Camera1.k1: {k['k1']}
Camera1.k2: {k['k2']}
Camera1.k3: {k['k3']}
Camera1.k4: {k['k4']}
Camera.width: {w}
Camera.height: {h}
Camera.fps: 20
Camera.RGB: 1
IMU.T_b_c1: !!opencv-matrix
   rows: 4
   cols: 4
   dt: f
   data: [{data}]
IMU.NoiseGyro: {ng}  # {sng}
IMU.NoiseAcc: {na}  # {sna}
IMU.GyroWalk: {gw}  # {sgw}
IMU.AccWalk: {aw}  # {saw}
IMU.Frequency: {rate}
# ORB extractor: ORB-SLAM3 TUM-VI defaults
ORBextractor.nFeatures: 1500
ORBextractor.scaleFactor: 1.2
ORBextractor.nLevels: 8
ORBextractor.iniThFAST: 20
ORBextractor.minThFAST: 7
{VIEWER}"""


def kitti(seq: Path) -> str:
    c2c = read_kitti_calib(find_up(seq, "calib_cam_to_cam.txt"))
    P = c2c["P_rect_02"].reshape(3, 4)
    w, h = (int(round(x)) for x in c2c["S_rect_02"])
    return f"""%YAML:1.0
# Generated by make_settings.py from calib_cam_to_cam.txt (P_rect_02, S_rect_02) of {seq.name}
File.version: "1.0"
Camera.type: "PinHole"
Camera1.fx: {P[0,0]}
Camera1.fy: {P[1,1]}
Camera1.cx: {P[0,2]}
Camera1.cy: {P[1,2]}
Camera1.k1: 0.0
Camera1.k2: 0.0
Camera1.p1: 0.0
Camera1.p2: 0.0
Camera.width: {w}
Camera.height: {h}
Camera.fps: 10
Camera.RGB: 1
# ORB extractor: ORB-SLAM3 KITTI odometry defaults
ORBextractor.nFeatures: 2000
ORBextractor.scaleFactor: 1.2
ORBextractor.nLevels: 8
ORBextractor.iniThFAST: 20
ORBextractor.minThFAST: 7
{VIEWER}"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dataset", choices=["tumvie", "kitti"])
    ap.add_argument("--seq", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()
    a.out.write_text(tumvie(a.seq) if a.dataset == "tumvie" else kitti(a.seq))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
