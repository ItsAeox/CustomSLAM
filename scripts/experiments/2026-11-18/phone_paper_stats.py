"""Pixel 9 batch (phone_1107) figures for the paper: bad runs phone vs PC browser module with the paper's tests,
per-frame tracking time on the phone, start-up time, battery temperature. Raw values, no ranking.

- Bad = no online trajectory or online Sim(3) ATE > 200 mm (as score_phone_1107.py); counts read from the scored runs.
- Tests: Fisher's exact test (two-sided) on the pooled counts, as everywhere in the paper; and an exact conditional
  test stratified by sequence (per sequence, phone bad runs ~ hypergeometric given that sequence's total; the strata
  convolved; two-sided = sum of probabilities <= the observed one). Runs are not paired by seed: a seed does not
  reproduce a run (paper, setup: repeats).
- Timing: track_times.txt column 2 (ms per processed frame, the tracking call in the page's worker), pooled over runs.
  Measured during the accuracy batch: viewer page, no rendering (viz=0), phone charging, one run at a time, battery
  temperature per run from runs.log.
Writes H:/Research/results/phone_1107/PAPER_PHONE.md.
Usage: python phone_paper_stats.py"""
import json, re
from pathlib import Path

import numpy as np
from scipy.stats import fisher_exact, hypergeom

P = Path("H:/Research/results/phone_1107")
PC = Path("H:/Research/results/main_1103")  # not read: the PC side comes from the scorer's own table (below)
ARMS = ["stock", "fast", "next", "beta"]
BAD = 0.200


def online_ate(run_dir):
    m = run_dir / "metrics_online.json"
    if not m.exists():
        return None
    j = json.loads(m.read_text())
    return j["ate_sim3"]["rmse"]


def per_seq_counts(md, arm):
    """phone / PC bad counts per EuRoC sequence from RESULTS.md's per-sequence table (written by score_phone_1107.py)"""
    lines = [l for l in md.splitlines() if l.startswith("| ") and "_" in l.split("|")[1]]
    hdr = next(l for l in md.splitlines() if l.startswith("| sequence | stock pixel9"))
    cols = [c.strip() for c in hdr.strip("|").split("|")]
    ip, ic = cols.index(f"{arm} pixel9"), cols.index(f"{arm} PC")
    out = []
    for l in lines:
        c = [x.strip() for x in l.strip("|").split("|")]
        if not re.match(r"(MH|V[12])_", c[0]):
            continue
        g = lambda s: int(re.search(r"\((\d+)/5\)", s).group(1))
        out.append((c[0], g(c[ip]), g(c[ic])))
    return out


def stratified_exact(st, n=5):
    dist, obs = np.array([1.0]), 0
    for _, p, c in st:
        t = p + c; obs += p
        dist = np.convolve(dist, [hypergeom.pmf(x, 2 * n, t, n) for x in range(0, min(t, n) + 1)])
    return float(dist[dist <= dist[obs] * (1 + 1e-9)].sum())


def times(arm, ds_glob):
    a = [np.loadtxt(f, usecols=1, ndmin=1) for f in sorted(P.glob(f"{arm}/{ds_glob}/web_seed*/track_times.txt"))]
    return a


def run_info(arm, ds_glob, key):
    v = []
    for f in sorted(P.glob(f"{arm}/{ds_glob}/web_seed*/run_info.txt")):
        for line in f.read_text().splitlines():
            if line.startswith(key + " "):
                v.append(float(line.split()[1]))
    return v


def main():
    md = (P / "RESULTS.md").read_text(encoding="utf-8")
    out = ["# Pixel 9 batch (phone_1107): figures for the paper", "",
           "Generated by CustomSLAM/scripts/experiments/2026-11-18/phone_paper_stats.py from results/phone_1107 "
           "(RESULTS.md and the runs). Raw values, no ranking.", "",
           "## Bad runs, EuRoC, phone vs PC browser module (55 runs each)", "",
           "| arm | phone bad | PC bad | Fisher exact p (two-sided) | exact test stratified by sequence, p (two-sided) |",
           "|---|---|---|---|---|"]
    for arm in ARMS:
        st = per_seq_counts(md, arm)
        p, c = sum(x[1] for x in st), sum(x[2] for x in st)
        out.append(f"| {arm} | {p} | {c} | {fisher_exact([[p, 55 - p], [c, 55 - c]])[1]:.4f} | {stratified_exact(st):.4f} |")
    out += ["", "Per sequence (phone / PC bad of 5):", ""]
    seqs = [s for s, _, _ in per_seq_counts(md, "stock")]
    out += ["| sequence | " + " | ".join(ARMS) + " |", "|---|" + "---|" * len(ARMS)]
    tab = {a: {s: (p, c) for s, p, c in per_seq_counts(md, a)} for a in ARMS}
    for s in seqs:
        out.append(f"| {s} | " + " | ".join(f"{tab[a][s][0]} / {tab[a][s][1]}" for a in ARMS) + " |")
    out += ["", "## Bad runs, synthetic set, phone vs PC (84 runs each)", "",
            "| arm | phone bad | PC bad | Fisher exact p (two-sided) |", "|---|---|---|---|"]
    syn = re.findall(r"^\| (\w+) \| (pixel9|PC) \| 84 \| (\d+) \|", md.split("## Synthetic")[1], re.M)
    sb = {(a, s): int(b) for a, s, b in syn}
    for arm in ARMS:
        p, c = sb[(arm, "pixel9")], sb[(arm, "PC")]
        out.append(f"| {arm} | {p} | {c} | {fisher_exact([[p, 84 - p], [c, 84 - c]])[1]:.4f} |")

    out += ["", "## Tracking time per processed frame on the Pixel 9 (ms; all frames of all runs pooled)", "",
            "Viewer page, no rendering, phone charging, one run at a time, during the accuracy batch. EuRoC frames "
            "600x350 after the settings' resize, 20 Hz (50 ms per frame); synthetic 480x640, 30 Hz (33.3 ms).", "",
            "| arm | data | runs | frames | median | p95 | > 33 ms (%) | > 50 ms (%) | start-up (init_ms), median s |",
            "|---|---|---|---|---|---|---|---|---|"]
    for arm in ARMS:
        for name, g in [("EuRoC, all 11", "euroc_*"), ("MH_01_easy", "euroc_MH_01_easy"),
                        ("V1_02_medium", "euroc_V1_02_medium"), ("synthetic, all 42", "synth_*")]:
            r = times(arm, g)
            if not r:
                continue
            a = np.concatenate(r)
            init = run_info(arm, g, "init_ms")
            out.append(f"| {arm} | {name} | {len(r)} | {a.size} | {np.median(a):.1f} | {np.percentile(a, 95):.1f} | "
                       f"{100 * np.mean(a > 33.3):.1f} | {100 * np.mean(a > 50):.1f} | "
                       f"{np.median(init) / 1000 if init else float('nan'):.2f} |")
    temps = [float(t) for t in re.findall(r"ok ph1107_\w+ .*?\| battery \d+% \S+ ([\d.]+) C",
                                           (P / "runs.log").read_text(encoding="utf-8"))]
    out += ["", f"Battery temperature at the start of the logged runs: {min(temps):.1f}-{max(temps):.1f} C "
            f"(median {np.median(temps):.1f} C, {len(temps)} log lines)."]
    rates = {}
    for arm in ARMS:
        for name, g in [("EuRoC", "euroc_*"), ("synthetic", "synth_*")]:
            v = run_info(arm, g, "effective_rate")
            rates[(arm, name)] = (np.mean(v), np.min(v), len(v)) if v else None
    out += ["", "Effective playback rate (1.00 = real time; every frame processed, none dropped): mean (min) per arm:", ""]
    for arm in ARMS:
        e, s = rates[(arm, "EuRoC")], rates[(arm, "synthetic")]
        out.append(f"- {arm}: EuRoC {e[0]:.2f} (min {e[1]:.2f}, {e[2]} runs); synthetic {s[0]:.2f} (min {s[1]:.2f}, {s[2]} runs)")
    (P / "PAPER_PHONE.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
