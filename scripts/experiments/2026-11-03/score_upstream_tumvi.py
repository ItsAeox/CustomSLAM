#!/usr/bin/env python3
"""Scores upstream_tumvi_1103 (upstream ORB-SLAM3 monocular on the TUM-VI rooms, ISSUES G39) next to the published
values and main_1103's native-stock port (its final trajectory, the largest map, as upstream's SaveTrajectoryEuRoC).
Sim(3) RMSE ATE of each run against the camera-frame GT (metrics.json) and the IMU-body GT (metrics_body.json).
Writes results/upstream_tumvi_1103/RESULTS.md. Usage: score_upstream_tumvi.py [--root H:/Research]
"""
import argparse
import json
import re
import statistics as st
from pathlib import Path

PUBLISHED = {1: 42, 2: 26, 3: 28, 4: 46, 5: 46, 6: 43}  # T-RO Table IV, monocular, mm (reported_values.md)
BAD_MM = 200


def load(p):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def ate_mm(m):
    return None if m is None else 1000 * m["ate_sim3"]["rmse"]


def fmt(v):
    return "–" if v is None else f"{v:.0f}"


def med(v):
    v = [x for x in v if x is not None]
    return st.median(v) if v else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path("/mnt/h/Research"))
    a = ap.parse_args()
    up, port = a.root / "results/upstream_tumvi_1103", a.root / "results/main_1103"
    L = ["# upstream_tumvi_1103: upstream ORB-SLAM3 monocular on the TUM-VI rooms", "",
         "Generated by scripts/experiments/2026-11-03/score_upstream_tumvi.py. Upstream = ORB-SLAM3 v1.0 4452a3c with two "
         "compile-only edits (-std=c++17; bool mnFullBAIdx++ -> = true), its own mono_tum_vi example, TUM-VI.yaml, "
         "timestamp files and CLAHE, real-time sleep as in the example, 3 runs at a time (user OK 3 Nov). Its output is "
         "the camera trajectory of the largest map. Port = main_1103 native-stock, final trajectory (largest map), 5 "
         "runs, rt-wall, 4 runs at a time. ATE = Sim(3) RMSE, mm, our evaluator (eval/evaluate.py). Camera = camera-frame "
         "GT (T_W_B * T_B_C); body = the IMU-body mocap poses. Bad = ATE > 200 mm or no trajectory. Medians over all runs "
         "(ORB-SLAM3's protocol: median of executions).", "",
         "| room | published (median of 3) | upstream, camera: median (runs) | bad | upstream, body: median | coverage, median | maps in atlas | port native-stock final, camera: median (runs) | port bad |",
         "|---|---|---|---|---|---|---|---|---|"]
    per_run = ["", "Per run (camera / body mm, coverage, maps):", ""]
    for k in range(1, 7):
        runs = sorted((up / f"room{k}").glob("run*"))
        cam, body, cov, maps = [], [], [], []
        for r in runs:
            m, mb = load(r / "metrics.json"), load(r / "metrics_body.json")
            log = (r / "run.log").read_text(errors="replace") if (r / "run.log").exists() else ""
            nm = re.findall(r"There are (\d+) maps in the atlas", log)
            cam.append(ate_mm(m))
            body.append(ate_mm(mb))
            cov.append(None if m is None else m["coverage"])
            maps.append(int(nm[-1]) if nm else None)
            per_run.append(f"- room{k} {r.name}: {fmt(cam[-1])} / {fmt(body[-1])}, "
                           f"{'–' if cov[-1] is None else f'{cov[-1]:.2f}'}, {maps[-1] if maps[-1] is not None else '–'}")
        pd = sorted((port / "native-stock" / f"tumvi_dataset-room{k}_512_16").glob("native_seed*"))
        pc = [ate_mm(load(d / "metrics.json")) for d in pd]
        bad = sum(v is None or v > BAD_MM for v in cam)
        pbad = sum(v is None or v > BAD_MM for v in pc)
        mm = [x for x in maps if x is not None]
        L.append(f"| {k} | {PUBLISHED[k]} | {fmt(med(cam))} ({', '.join(fmt(v) for v in cam)}) | {bad} of {len(cam)} | "
                 f"{fmt(med(body))} | {'–' if med(cov) is None else f'{med(cov):.2f}'} | "
                 f"{(str(min(mm)) + '–' + str(max(mm))) if mm else '–'} | {fmt(med(pc))} ({', '.join(fmt(v) for v in pc)}) | "
                 f"{pbad} of {len(pc)} |")
    out = "\n".join(L + per_run) + "\n"
    (up / "RESULTS.md").write_text(out, encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
