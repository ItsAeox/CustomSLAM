#!/usr/bin/env python3
"""Compares equiv_1103 (equiv_1103.sh): for each arm and sequence, the final trajectory (traj_tum.txt) of the pre-cut
build (snap-f1a4a97) against the frozen build (snap-84c1f17), and the frozen build against itself (frozen2: is the
mode deterministic?). Identical = byte-identical files; otherwise the largest position difference over common
timestamps and both Sim(3) ATEs. Writes results/equiv_1103/EQUIV.md. Usage: equiv_compare.py [--root H:/Research]
"""
import argparse
import json
from pathlib import Path


def traj(p):
    d = {}
    for l in p.read_text(encoding="utf-8").splitlines():
        if l and not l.startswith("#"):
            v = l.split()
            d[v[0]] = tuple(float(x) for x in v[1:4])
    return d


def ate(p):
    try:
        return f"{1000 * json.loads(p.read_text(encoding='utf-8'))['ate_sim3']['rmse']:.1f}"
    except (OSError, ValueError, KeyError):
        return "–"


def compare(a, b):
    fa, fb = a / "traj_tum.txt", b / "traj_tum.txt"
    if not fa.exists() or not fb.exists():
        return "missing"
    if fa.read_bytes() == fb.read_bytes():
        return "identical"
    ta, tb = traj(fa), traj(fb)
    common = set(ta) & set(tb)
    dmax = max((sum((x - y) ** 2 for x, y in zip(ta[t], tb[t])) ** 0.5 for t in common), default=float("nan"))
    return f"differs: {len(ta)} / {len(tb)} poses, {len(common)} common, max position difference {dmax:.3g} (map units)"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path("/mnt/h/Research"))
    a = ap.parse_args()
    r = a.root / "results/equiv_1103"
    L = ["# equiv_1103: pre-cut build (snap-f1a4a97, 19 Oct 01:34) vs frozen build (snap-84c1f17, 3 Nov)", "",
         "Generated by scripts/experiments/2026-11-03/equiv_compare.py. Native runner, unpaced, --sync-mapping, seed 1, "
         "first 1500 frames, main_1103's settings files. Final trajectory (largest map) compared byte for byte; ATE = "
         "Sim(3) RMSE, mm, over the frames run.", "",
         "| arm | sequence | frozen vs frozen (determinism) | pre-cut vs frozen | ATE pre / frozen / frozen2 |", "|---|---|---|---|---|"]
    for arm in ["stock", "fast", "next", "beta"]:
        for sd in sorted((r / "frozen" / arm).glob("*")):
            pre, fr, fr2 = r / "pre" / arm / sd.name, sd, r / "frozen2" / arm / sd.name
            L.append(f"| {arm} | {sd.name} | {compare(fr, fr2)} | {compare(pre, fr)} | "
                     f"{ate(pre / 'metrics.json')} / {ate(fr / 'metrics.json')} / {ate(fr2 / 'metrics.json')} |")
    out = "\n".join(L) + "\n"
    (r / "EQUIV.md").write_text(out, encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
