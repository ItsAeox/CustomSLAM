#!/usr/bin/env python3
"""TUM-VI audit (VII §D): our TUM-VI ATE is the camera trajectory against camera-frame ground truth
(T_W_B * T_B_C, eval/gt_asl.py). ORB-SLAM3's only released TUM-VI evaluation (v0.3-beta tum_vi_eval_examples.sh)
scores against mav0/mocap0/data.csv, the IMU-body poses. This re-scores main_1103's TUM-VI runs against the body-frame
ground truth (results/gt/tumvi_<seq>_body.txt, same exporter with --frame body) with the same evaluate.py, final and
online trajectories, so the two conventions can be shown side by side. Nothing in the run folders is changed.

Usage: tumvi_frame_audit.py [--root results/main_1103] [--out results/main_1103/tumvi_body]
Writes <out>/<arm>/<seq>/<run>/{metrics,metrics_online}.json and <out>/TUMVI_FRAMES.md.
"""
import argparse
import json
import statistics as st
import subprocess
import sys
from pathlib import Path

R = Path("/mnt/h/Research")
ARMS = ["native-stock", "wasm-stock", "page-fast", "page-next", "page-beta", "page-betagyro", "page-mapfirst"]
PUBLISHED = {"room1": 42, "room2": 26, "room3": 28, "room4": 46, "room5": 46, "room6": 43}  # ORB-SLAM3 T-RO Table IV, mono


def ate(p):
    try:
        return json.loads(p.read_text())["ate_sim3"]["rmse"]
    except (OSError, ValueError, KeyError):
        return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=R / "results/main_1103")
    ap.add_argument("--out", type=Path, default=R / "results/main_1103/tumvi_body")
    a = ap.parse_args()
    ev = R / "CustomSLAM/eval/evaluate.py"
    cell = {}
    for arm in ARMS:
        for sd in sorted((a.root / arm).glob("tumvi_*")):
            seq = sd.name[len("tumvi_"):]
            gt = R / f"results/gt/tumvi_{seq}_body.txt"
            for d in sorted(sd.glob("*_seed*")):
                o = a.out / arm / sd.name / d.name
                o.mkdir(parents=True, exist_ok=True)
                for est, name in (("traj_tum.txt", "metrics.json"), ("online_tum.txt", "metrics_online.json")):
                    if (d / est).exists() and (d / est).stat().st_size and not (o / name).exists():
                        subprocess.run([sys.executable, str(ev), "--gt", str(gt), "--est", str(d / est), "--out",
                                        str(o / name), "--label", f"body {arm} {seq} {d.name}"],
                                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                room = seq.split("-")[1].split("_")[0]
                c = cell.setdefault((arm, room), {"cf": [], "co": [], "bf": [], "bo": []})
                c["cf"].append(ate(d / "metrics.json"))
                c["co"].append(ate(d / "metrics_online.json"))
                c["bf"].append(ate(o / "metrics.json"))
                c["bo"].append(ate(o / "metrics_online.json"))

    def m(v):  # median of all runs, no trajectory = worst (as VII §B-D)
        v = [x if x is not None else float("inf") for x in v]
        x = st.median(v) if v else None
        return "–" if x is None else ("fail" if x == float("inf") else f"{1000 * x:.0f}")

    rooms = sorted({r for _, r in cell})
    L = ["# TUM-VI rooms: camera-frame vs body-frame ground truth (main_1103 runs)", "",
         "Generated by scripts/experiments/2026-11-03/tumvi_frame_audit.py. Sim(3) RMSE (mm), median of all 5 runs "
         "(no trajectory = worst). camera = our convention (camera trajectory vs T_W_B·T_B_C); body = the camera "
         "trajectory against the IMU-body poses of mocap0, as ORB-SLAM3's released TUM-VI evaluation script scores "
         "(v0.3-beta tum_vi_eval_examples.sh, written for stereo-inertial output). ORB-SLAM3 column: published "
         "monocular values (T-RO 2021 Table IV, median of 3 runs); the paper does not say which frame they were "
         "scored in.", "",
         "## Final trajectory (camera / body)", "", "| room | ORB-SLAM3 (published) | " + " | ".join(ARMS) + " |",
         "|---|---|" + "---|" * len(ARMS)]
    for r in rooms:
        L.append(f"| {r} | {PUBLISHED.get(r, '')} | " + " | ".join(
            f"{m(cell[(arm, r)]['cf'])} / {m(cell[(arm, r)]['bf'])}" if (arm, r) in cell else "" for arm in ARMS) + " |")
    L += ["", "## Online poses (camera / body)", "", "| room | " + " | ".join(ARMS) + " |", "|---|" + "---|" * len(ARMS)]
    for r in rooms:
        L.append(f"| {r} | " + " | ".join(
            f"{m(cell[(arm, r)]['co'])} / {m(cell[(arm, r)]['bo'])}" if (arm, r) in cell else "" for arm in ARMS) + " |")
    (a.out / "TUMVI_FRAMES.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
