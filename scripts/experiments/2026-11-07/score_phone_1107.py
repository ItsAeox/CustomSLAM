"""score_phone_1107: each phone's runs (phone_convert_1107.py output) next to the PC browser-module runs of the same
arm, sequence and seed (main_1103 for EuRoC, ext_1103 for the synthetic set), raw, no ranking (claude/EXPERIMENTS.md
phone_1107). Only (sequence, seed) pairs the phone has are used on both sides, so a part-finished phone batch is
compared like for like.

Per run, as score_main_1103.py: online Sim3 ATE and coverage (metrics_online.json), final Sim3 ATE (metrics.json),
bad = no online trajectory or online ATE > 200 mm. Per arm and dataset: runs, bad runs, median over sequences of the
per-sequence median good-run online ATE, mean online coverage, median final ATE of good final trajectories, mean
effective rate; then the phone / PC ratio of per-sequence median good-run online ATE (median over sequences).

Usage: python score_phone_1107.py [--dev pixel9|a07|...]  ->  results/phone_1107[_<dev>]/RESULTS.md"""
import argparse, json, statistics as st
from pathlib import Path

R = Path("H:/Research/results")
PC = {"euroc": R / "main_1103", "synth": R / "ext_1103"}
PCARM = {"stock": "wasm-stock", "fast": "page-fast", "next": "page-next", "beta": "page-beta"}
ARMS = ["stock", "fast", "next", "beta"]
BAD = 0.200


def jl(p):
    try:
        return json.loads(p.read_text())
    except (OSError, ValueError):
        return None


def row(d):
    on, fi = jl(d / "metrics_online.json"), jl(d / "metrics.json")
    ri = {}
    if (d / "run_info.txt").exists():
        for l in (d / "run_info.txt").read_text().splitlines():
            k, _, v = l.partition(" ")
            ri[k] = v
    r = {"on": on["ate_sim3"]["rmse"] if on else None, "cov": on["coverage"] if on else 0.0,
         "fin": fi["ate_sim3"]["rmse"] if fi else None,
         "rate": float(ri["effective_rate"]) if ri.get("effective_rate") not in (None, "None") else None}
    r["bad"] = r["on"] is None or r["on"] > BAD
    return r


def med(v):
    v = [x for x in v if x is not None]
    return st.median(v) if v else None


def mm(x):
    return "–" if x is None else f"{x * 1000:.1f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dev", default="pixel9")
    a = ap.parse_args()
    root = R / ("phone_1107" if a.dev == "pixel9" else f"phone_1107_{a.dev}")
    runs = {}  # (side, arm, ds, seq) -> {seed: row}
    for arm in ARMS:
        for d in sorted((root / arm).glob("*/web_seed*")):
            ds, seq = d.parent.name.split("_", 1)
            seed = d.name.removeprefix("web_seed")
            pcd = PC[ds] / PCARM[arm] / d.parent.name / f"wasm_seed{seed}"
            if not pcd.exists():
                continue
            runs.setdefault(("phone", arm, ds, seq), {})[seed] = row(d)
            runs.setdefault(("pc", arm, ds, seq), {})[seed] = row(pcd)
    out = [f"# phone_1107 — {a.dev} vs PC browser module (same arm, sequence and seed)", "",
           "Generated by CustomSLAM/scripts/experiments/2026-11-07/score_phone_1107.py. Raw values, no ranking. "
           "Online = the pose each frame got live; final = ORB-SLAM3's trajectory after shutdown. Bad = no online "
           "trajectory or online Sim3 ATE > 200 mm. ATE columns: median over sequences of the per-sequence median of "
           "good runs (mm). Rate = sequence time / processing time (nothing is dropped).", ""]
    for ds, name in (("euroc", "EuRoC (11 sequences)"), ("synth", "Synthetic core set (42 sequences)")):
        out += [f"## {name}", "",
                "| arm | side | runs | bad | online ATE | online coverage | final ATE (good) | rate (mean) | phone/PC online ATE |",
                "|---|---|---|---|---|---|---|---|---|"]
        for arm in ARMS:
            seqs = sorted(s for (side, ar, d_, s) in runs if side == "phone" and ar == arm and d_ == ds)
            if not seqs:
                continue
            ratios = []
            for s in seqs:
                p = med([r["on"] for r in runs[("phone", arm, ds, s)].values() if not r["bad"]])
                q = med([r["on"] for r in runs[("pc", arm, ds, s)].values() if not r["bad"]])
                if p and q:
                    ratios.append(p / q)
            for side in ("phone", "pc"):
                rr = [r for s in seqs for r in runs[(side, arm, ds, s)].values()]
                persq = [med([r["on"] for r in runs[(side, arm, ds, s)].values() if not r["bad"]]) for s in seqs]
                rates = [r["rate"] for r in rr if r["rate"] is not None]
                out.append(f"| {arm} | {a.dev if side == 'phone' else 'PC'} | {len(rr)} | {sum(r['bad'] for r in rr)} | "
                           f"{mm(med(persq))} | {st.mean(r['cov'] for r in rr):.2f} | "
                           f"{mm(med([r['fin'] for r in rr if r['fin'] is not None and r['fin'] <= BAD]))} | "
                           f"{st.mean(rates):.2f} | "
                           f"{(f'{st.median(ratios):.2f} ({sum(x < 1 for x in ratios)}/{len(ratios)} seq lower on phone)' if ratios and side == 'phone' else '')} |")
        out.append("")
        if ds == "euroc":
            out += ["### EuRoC per sequence: median good-run online ATE, mm (bad runs / runs)", "",
                    "| sequence | " + " | ".join(f"{arm} {a.dev} | {arm} PC" for arm in ARMS) + " |",
                    "|---|" + "---|" * (2 * len(ARMS))]
            for s in sorted({s for (side, ar, d_, s) in runs if d_ == "euroc"}):
                cells = []
                for arm in ARMS:
                    for side in ("phone", "pc"):
                        v = runs.get((side, arm, "euroc", s), {}).values()
                        cells.append(f"{mm(med([r['on'] for r in v if not r['bad']]))} ({sum(r['bad'] for r in v)}/{len(v)})")
                out.append(f"| {s} | " + " | ".join(cells) + " |")
            out.append("")
    (root / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
