#!/usr/bin/env python3
"""Scores return_1104 (return_1104.sh: the leave-and-return AR test, presets in the paper's scope, frozen build) from the
per-run eval/anchor_return.py files, live@1.0 and phone pace, per scenario, arm and placement: centre (anchor.txt, the
scorer's centre depth as in the earlier return batches), floor (anchor_floor.txt, the pre-cut page's floor plane) and best
fixed (anchor_oracle.txt: the anchor that best fits the true spot in the placement map, i.e. the map's own error).
Placed = the object went down; back = of the placed runs, shown again on the return; wait = from the spot first in view
on the return to the object first shown (median, min-max, of the runs back); px = median over runs of the run's median
screen error while shown (all frames after placing / return frames only); > 50 px = runs whose median is over 50 px.
Writes results/return_1104/RESULTS.md. Usage: score_return_1104.py [--root H:/Research]
"""
import argparse
import re
import statistics as st
from collections import defaultdict
from pathlib import Path

PLACEMENTS = (("centre", "anchor.txt"), ("floor", "anchor_floor.txt"), ("best fixed", "anchor_oracle.txt"))
ARMS = ("stock", "fast", "next", "beta", "beta_newmap")
SCENARIOS = (("flat", "S11: place on a 5.8 s old map, leave through the flat, come back"),
             ("flatmap", "S12: place, walk around the bedroom, leave, come back"),
             ("flatfirst", "S13: map the bedroom first, place at 32.79 s, leave, come back by the other door"))


def med(v, f="{:.1f}"):
    return f.format(st.median(v)) if v else "–"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path("/mnt/h/Research"))
    a = ap.parse_args()
    L = ["# return_1104: leave and return with an object placed, presets in the paper's scope", "",
         "Generated by scripts/experiments/2026-11-04/score_return_1104.py from eval/anchor_return.py per run. Frozen build "
         "snap-84c1f17, presets as the pre-cut page runs them (arms_return.txt): fast / next / beta keep the map once the "
         "object is placed, stock and beta_newmap start a new map after a loss (merge when the place is recognised). "
         "live@1.0 seeds 1-3, phone pace (rate-scale 0.25) seeds 1-2. Keep-map placement counts are pessimistic: the "
         "runner turns keep on without the spot in view, the scorer needs it within 40 px, so a young map kept and lost "
         "scores 'not placed' where a new map would re-place (flatkeep_1101).", ""]
    for pace, d in (("live@1.0", "return_1104"), ("phone pace (0.25)", "return_1104_phone")):
        root = a.root / "results" / d
        R = defaultdict(list)
        for f in sorted(root.glob("*/*/seed*/anchor*.txt")):
            name = next((n for n, fn in PLACEMENTS if fn == f.name), None)
            if name is None:
                continue
            sc, arm = re.sub(r"\d+$", "", f.parts[-4]), f.parts[-3]
            R[(sc, arm, name)].append(dict(re.findall(r"(\w+)=(\S+)", f.read_text(encoding="utf-8", errors="replace"))))
        for sc, desc in SCENARIOS:
            L += [f"## {sc}, {pace}", "", desc, "",
                  "| arm | placement | runs | placed | back on return | wait s, median (min–max) | px median | runs > 50 px | "
                  "return px median | shown % after placing, median | maps per run, median (max) |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
            for arm in ARMS:
                for name, _ in PLACEMENTS:
                    rs = R.get((sc, arm, name), [])
                    if not rs:
                        continue
                    pl = [r for r in rs if r.get("placed") == "1"]
                    back = [r for r in pl if float(r.get("ret_shown_pct", 0) or 0) > 0]
                    w = [float(r["ret_wait_s"]) for r in back if float(r.get("ret_wait_s", -1)) >= 0]
                    px = [float(r["px_med"]) for r in pl if r.get("px_med", "-") not in ("-", "")]
                    rpx = [float(r["ret_px_med"]) for r in back if r.get("ret_px_med", "-") not in ("-", "")]
                    sh = [float(r["shown_pct"]) for r in pl if r.get("shown_pct", "-") not in ("-", "")]
                    mx = [int(r["maps_max"]) for r in rs if r.get("maps_max", "-").isdigit()]
                    ws = f"{st.median(w):.1f} ({min(w):.1f}–{max(w):.1f})" if w else "–"
                    L.append(f"| {arm} | {name} | {len(rs)} | {len(pl)} | {len(back)} | {ws} | {med(px)} | "
                             f"{sum(x > 50 for x in px)} | {med(rpx)} | {med(sh, '{:.0f}')} | "
                             f"{med(mx, '{:.0f}')} ({max(mx) if mx else '–'}) |")
            L.append("")
    out = "\n".join(L) + "\n"
    (a.root / "results/return_1104/RESULTS.md").write_text(out, encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
