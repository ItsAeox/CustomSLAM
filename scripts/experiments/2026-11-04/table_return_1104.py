#!/usr/bin/env python3
"""One table per pace for the paper (VII, AR section) from return_1104's scored files, floor placement (the pre-cut page's):
RESULTS.md (score_return_1104.py: placed, back, wait, px, maps), RETSNAP.md (ret_snap.py --place floor: right again within
15 px for 2 s), PHASE.md (track_phase.py: tracked % of the walk out and back) and COLLAPSE.md of each batch dir
(eval/scale_collapse.py: a map's scale spread over its 3 s windows > 5x), and RET_WRONG.md (ret_wrong_1104.py, 4 Nov: on
screen again = shown on a return frame and inside the image; the counts under the page's stashAnchors rule; the runs back
and not right by cause). Writes results/return_1104/PAPER_TABLE.md.
Usage: table_return_1104.py [--root H:/Research]
"""
import argparse
import re
from pathlib import Path

ARMS = ("stock", "fast", "next", "beta", "beta_newmap")
SCENARIOS = ("flat", "flatmap", "flatfirst")
PACES = (("live@1.0", "return_1104"), ("phone pace (0.25)", "return_1104_phone"))


def cells(l):
    return [c.strip() for c in l.strip().strip("|").split("|")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path("/mnt/h/Research"))
    a = ap.parse_args()
    r0 = a.root / "results/return_1104"
    res, snap, walk, col, wr = {}, {}, {}, {}, {}
    sec = None
    for l in (r0 / "RESULTS.md").read_text(encoding="utf-8").splitlines():
        if l.startswith("## "):
            sec = l[3:]
        elif l.startswith("| ") and sec and cells(l)[1] == "floor":
            sc, pace = sec.split(", ", 1)
            res[(pace, sc, cells(l)[0])] = cells(l)
    for l in (r0 / "RETSNAP.md").read_text(encoding="utf-8").splitlines():
        if l.startswith("### "):
            sec = l[4:] if "floor" in l else None
        elif l.startswith("| flat") and sec:
            c = cells(l)
            snap[(sec.split()[0], c[0], c[1])] = c
    for l in (r0 / "PHASE.md").read_text(encoding="utf-8").splitlines():
        if l.startswith("## "):
            sec = l[3:].split()
        elif l.startswith("| ") and sec and cells(l)[0] in ARMS:
            walk[(sec[0], sec[1], cells(l)[0])] = cells(l)[4]
    for _, d in PACES:
        for l in (a.root / "results" / d / "COLLAPSE.md").read_text(encoding="utf-8").splitlines():
            if l.startswith("| flat"):
                c = cells(l)
                col[(d, c[0], c[1])] = f"{c[3]} of {c[2]}"
    for l in (r0 / "RET_WRONG.md").read_text(encoding="utf-8").splitlines():
        if l.startswith("| live |") or l.startswith("| phone |"):
            c = cells(l)
            wr[("return_1104" if c[0] == "live" else "return_1104_phone", c[1], c[2])] = c
    L = ["# return_1104: paper table (floor placement = the pre-cut page's)", "",
         "Generated by scripts/experiments/2026-11-04/table_return_1104.py from RESULTS.md, RETSNAP.md, PHASE.md and "
         "COLLAPSE.md, RET_WRONG.md. Back on return (the page's visible flag), on screen again and right again are "
         "counts of the placed runs. Page stash rule: the same counts when the page's stashAnchors replacing the stash "
         "at a second new map is applied (only stock / beta_newmap start new maps after placing).", ""]
    for pace, d in PACES:
        L += [f"## {pace}", "",
              "| scenario | arm | placed | back on return | on screen again | wait s, median (min–max) | right again "
              "(< 15 px for 2 s) | time to right s, median | px median while shown | runs > 50 px | walk tracked %, median | "
              "maps per run, median (max) | collapsed | page stash rule: on screen / right again |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for sc in SCENARIOS:
            for arm in ARMS:
                c, s, w = res[(pace, sc, arm)], snap.get((d, sc, arm), ["–"] * 6), wr[(d, sc, arm)]
                t = s[4].split(" ")[0] if s[4] != "-" else "–"
                assert w[4] == c[4] and w[7] == s[3], (pace, sc, arm, w, c[4], s[3])  # the same runs counted
                L.append(f"| {sc} | {arm} | {c[3]} of {c[2]} | {c[4]} | {w[5]} | {c[5]} | {s[3]} | {t} | {c[6]} | {c[7]} | "
                         f"{walk[(d, sc, arm)].split(' ')[0]} | {c[10]} | {col[(d, sc, arm)]} | {w[6]} / {w[8]} |")
        L += ["", f"Back on return but not right again, by cause ({pace}; ret_wrong_1104.py, first rule that holds):", "",
              "| scenario | arm | back, not right | merged with another map | collapsed at placement | wrong before leaving | "
              "near miss (< 50 px) | other | of them never on screen |", "|---|---|---|---|---|---|---|---|---|"]
        for sc in SCENARIOS:
            for arm in ARMS:
                w = wr[(d, sc, arm)]
                L.append(f"| {sc} | {arm} | " + " | ".join(w[9:16]) + " |")
        L.append("")
    out = "\n".join(L) + "\n"
    (r0 / "PAPER_TABLE.md").write_text(out, encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
