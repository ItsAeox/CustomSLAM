"""Writes web/study/kx.html (the WebVIO condition of the blind user study, claude/STUDY.md) from web/ar.html: the same
page and script with <base href="../"> (so every relative URL resolves as for ar.html) and the study-mode CSS that
hides the panels, hints and start screen (ar.js study=1 starts by itself). Run after changing ar.html."""
from pathlib import Path

W = Path(__file__).resolve().parent.parent / "web"
s = (W / "ar.html").read_text(encoding="utf-8")
a = '<meta charset="utf-8">'
assert s.count(a) == 1
s = s.replace(a, a + '\n<base href="../">', 1)
s = s.replace("<title>WebVIO AR</title>", "<title>AR study</title>", 1)
css = ("<style>body.study #hud, body.study #hint, body.study #ghost, body.study #cubeInfo, body.study #menuBtn, body.study #infoBtn,"
       " body.study #bar, body.study #miniWrap, body.study #topRow, body.study #sizeRow, body.study #usage, body.study #log,"
       " body.study #start { display: none !important; }</style>\n</head>")
assert s.count("</head>") == 1
s = s.replace("</head>", css, 1)
s = s.replace("<!doctype html>", "<!doctype html>\n<!-- generated by scripts/make_study_pages.py from web/ar.html: do not edit -->", 1)
(W / "study" / "kx.html").write_text(s, encoding="utf-8", newline="\n")
print("web/study/kx.html written")
